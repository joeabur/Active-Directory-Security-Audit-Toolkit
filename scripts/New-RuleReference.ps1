<#
.SYNOPSIS
    Generates docs/rule-reference.md from the rule catalog so documentation cannot drift from the code.
.EXAMPLE
    ./scripts/New-RuleReference.ps1
#>
[CmdletBinding()]
param([string] $OutputFile = (Join-Path (Split-Path -Path $PSScriptRoot -Parent) 'docs/rule-reference.md'))
Set-StrictMode -Version 2.0
$root = Split-Path -Path $PSScriptRoot -Parent
Import-Module (Join-Path $root 'src/ADSecurityAudit.psd1') -Force
$rules = Get-ADSARuleCatalog
$sb = New-Object System.Text.StringBuilder
$null = $sb.AppendLine('# Rule reference')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('<!-- Generated by scripts/New-RuleReference.ps1 from src/Rules/RuleCatalog.psd1. Do not edit by hand. -->')
$null = $sb.AppendLine('')
$null = $sb.AppendLine("The toolkit implements $(@($rules).Count) rules. Every rule has a stable ID, a default severity and confidence, a finding type, remediation guidance, limitations and the permission it needs. Severity and confidence can be overridden per finding (for example ADSA-ACL-001 raises severity when the principal is broad). Rules assess selected, well-defined conditions; they do not claim to detect every Active Directory attack path.")
$null = $sb.AppendLine('')
$null = $sb.AppendLine('Finding types: **Hygiene** (clean-up evidence, not a confirmed vulnerability), **Misconfiguration** (a setting that weakens security), **PotentialRisk** (needs human judgement), **Informational**.')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('| Rule | Module | Severity | Confidence | Type | Title |')
$null = $sb.AppendLine('|---|---|---|---|---|---|')
foreach ($r in $rules) { $null = $sb.AppendLine("| [$($r.Id)](#$($r.Id.ToLowerInvariant())) | $($r.Module) | $($r.Severity) | $($r.Confidence) | $($r.FindingType) | $($r.Title) |") }
foreach ($r in $rules) {
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine("## $($r.Id)")
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine("**$($r.Title)**")
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine("- Category: $($r.Category) | Module: $($r.Module) | Severity: $($r.Severity) | Confidence: $($r.Confidence) | Type: $($r.FindingType)")
    $null = $sb.AppendLine("- Data collected: $($r.RequiredData)")
    $null = $sb.AppendLine("- Permission needed: $($r.Permissions)")
    $null = $sb.AppendLine("- What it means: $($r.Description)")
    $null = $sb.AppendLine("- Remediation: $($r.Remediation)")
    $null = $sb.AppendLine("- Limitations: $($r.Limitations)")
}
[System.IO.File]::WriteAllText($OutputFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Information "Wrote $OutputFile" -InformationAction Continue
